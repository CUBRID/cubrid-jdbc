package cubrid.jdbc.lb;

import java.io.UnsupportedEncodingException;
import java.sql.Connection;
import java.sql.SQLException;
import java.util.concurrent.Executor;

/**
 * The session properties core keeps on its one connection, which LB keeps for every leg (review r5,
 * recommendation 2-5). Each is one row here, holding the value the application gave and how a leg
 * takes it; a setter puts the value on the legs open now, and a leg opened later gets every row
 * that has one ({@link #applyTo}). Until the application sets a property, every leg keeps its own,
 * as a core connection keeps the server's. {@code SessionPropertyTableTest} checks the rows against
 * core's setters.
 */
final class SessionProperties {

    /** One property: its value, null until the application sets one, and how a leg takes it. */
    abstract static class Property<V> {
        private volatile V value;

        V get() {
            return value;
        }

        void set(final V newValue) {
            value = newValue;
        }

        abstract void apply(Connection leg, V v) throws SQLException;
    }

    /** {@code setNetworkTimeout}'s two arguments. */
    static final class NetworkTimeout {
        final Executor executor;
        final int milliseconds;

        NetworkTimeout(final Executor executor, final int milliseconds) {
            this.executor = executor;
            this.milliseconds = milliseconds;
        }
    }

    final Property<NetworkTimeout> networkTimeout =
            new Property<NetworkTimeout>() {
                void apply(final Connection leg, final NetworkTimeout v) throws SQLException {
                    leg.setNetworkTimeout(v.executor, v.milliseconds);
                }
            };

    final Property<Integer> isolation =
            new Property<Integer>() {
                void apply(final Connection leg, final Integer v) throws SQLException {
                    leg.setTransactionIsolation(v.intValue());
                }
            };

    final Property<Integer> lockTimeout =
            new Property<Integer>() {
                void apply(final Connection leg, final Integer v) throws SQLException {
                    LoadBalanceConnection.extConn(leg, "setLockTimeout")
                            .setLockTimeout(v.intValue());
                }
            };

    final Property<Integer> casChangeMode =
            new Property<Integer>() {
                void apply(final Connection leg, final Integer v) throws SQLException {
                    LoadBalanceConnection.extConn(leg, "setCASChangeMode")
                            .setCASChangeMode(v.intValue());
                }
            };

    final Property<Boolean> autoGeneratedKeys =
            new Property<Boolean>() {
                void apply(final Connection leg, final Boolean v) throws SQLException {
                    LoadBalanceConnection.extConn(leg, "setAutoGeneratedKeys")
                            .setAutoGeneratedKeys(v.booleanValue());
                }
            };

    final Property<String> charset =
            new Property<String>() {
                void apply(final Connection leg, final String v) throws SQLException {
                    try {
                        LoadBalanceConnection.extConn(leg, "setCharset").setCharset(v);
                    } catch (UnsupportedEncodingException rejected) {
                        // A leg took the name once, so another rejecting it is a driver-level
                        // disagreement, not the caller's error; this method cannot throw it as is.
                        throw LbExceptions.invalidValue(
                                "setCharset("
                                        + v
                                        + ") was rejected when re-applied to a new leg: "
                                        + rejected.getMessage());
                    }
                }
            };

    final Property<Integer> holdability =
            new Property<Integer>() {
                void apply(final Connection leg, final Integer v) throws SQLException {
                    leg.setHoldability(v.intValue());
                }
            };

    /**
     * Gives a leg just opened every property that has a value, in this order: the network timeout
     * first, so every later request on the leg is bounded, then the autocommit mode, which the
     * session always has. A network timeout kept before any leg existed without an executor is not
     * given: core would refuse it.
     *
     * @param leg the leg just opened
     * @param autoCommit the session's autocommit mode
     * @throws SQLException if the leg refuses a property
     */
    void applyTo(final Connection leg, final boolean autoCommit) throws SQLException {
        final NetworkTimeout timeout = networkTimeout.get();
        if (timeout != null && timeout.executor != null) {
            networkTimeout.apply(leg, timeout);
        }
        leg.setAutoCommit(autoCommit);
        applyIfSet(isolation, leg);
        applyIfSet(lockTimeout, leg);
        applyIfSet(casChangeMode, leg);
        applyIfSet(autoGeneratedKeys, leg);
        applyIfSet(charset, leg);
        applyIfSet(holdability, leg);
    }

    private static <V> void applyIfSet(final Property<V> property, final Connection leg)
            throws SQLException {
        final V v = property.get();
        if (v != null) {
            property.apply(leg, v);
        }
    }
}
