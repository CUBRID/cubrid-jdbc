package cubrid.jdbc.lb;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;

import cubrid.jdbc.driver.CUBRIDConnection;
import cubrid.jdbc.driver.KitConnection;
import cubrid.jdbc.driver.KitServer;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.TreeSet;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import org.junit.After;
import org.junit.Test;

/**
 * Every setter core's connection has, and what a leg LB opens later gets of it (review r5,
 * recommendation 2-5). A setter core adds fails {@link #everyCoreSetterIsInTheTable} until it is
 * placed here; a property LB forgets to apply to a new leg fails {@link
 * #aLegOpenedLaterHasEveryAppliedProperty}.
 */
public class SessionPropertyTableTest {
    /** Applied again to every leg LB opens: what core's one connection keeps for its session. */
    static final String APPLIED = "applied to every leg LB opens";

    static final Map<String, String> SETTERS = new LinkedHashMap<String, String>();

    static {
        SETTERS.put("setAutoCommit", APPLIED);
        SETTERS.put("setTransactionIsolation", APPLIED);
        SETTERS.put("setLockTimeout", APPLIED);
        SETTERS.put("setCASChangeMode", APPLIED);
        SETTERS.put("setHoldability", APPLIED);
        SETTERS.put("setNetworkTimeout", APPLIED);
        SETTERS.put("setAutoGeneratedKeys", APPLIED);
        SETTERS.put("setCharset", APPLIED + "; core's UConnection.setCharset does nothing");
        SETTERS.put("setReadOnly", "core keeps nothing: isReadOnly() is always false");
        SETTERS.put("setCatalog", "core keeps nothing: getCatalog() is always empty");
        SETTERS.put("setSchema", "core changes nothing: it warns when asked for another schema");
        SETTERS.put("setClientInfo", "core refuses");
        SETTERS.put("setTypeMap", "core refuses");
        SETTERS.put("setSavepoint", "not a property: a savepoint belongs to the transaction");
    }

    private final LbKit kit = new LbKit(2);
    private final ExecutorService timeouts = Executors.newSingleThreadExecutor();

    @After
    public void tearDown() {
        kit.close();
        timeouts.shutdownNow();
    }

    @Test
    public void everyCoreSetterIsInTheTable() {
        final TreeSet<String> setters = new TreeSet<String>();
        for (Method m : CUBRIDConnection.class.getMethods()) {
            if (m.getName().startsWith("set")
                    && m.getDeclaringClass() != Object.class
                    && !Modifier.isStatic(m.getModifiers())) {
                setters.add(m.getName());
            }
        }
        assertEquals(new TreeSet<String>(SETTERS.keySet()), setters);
    }

    /** Each applied property, set before the write leg fails over, is on the new write leg. */
    @Test
    public void aLegOpenedLaterHasEveryAppliedProperty() throws Exception {
        final LoadBalanceConnection conn = kit.open("readWeight=slave:1");
        conn.setTransactionIsolation(Connection.TRANSACTION_SERIALIZABLE);
        conn.setLockTimeout(7);
        conn.setCASChangeMode(CUBRIDConnection.CAS_CHANGE_MODE_KEEP);
        conn.setHoldability(ResultSet.CLOSE_CURSORS_AT_COMMIT);
        conn.setNetworkTimeout(timeouts, 3000);
        conn.setAutoGeneratedKeys(true);

        kit.server.fault(kit.rw(1), KitServer.Fault.REFUSE);
        try {
            conn.createStatement().executeUpdate("UPDATE t SET a = 1");
        } catch (SQLException moved) {
            // the write leg moves to node 2
        }
        final KitConnection leg = liveLegOn(kit.rw(2));

        assertTrue(leg.getAutoCommit());
        assertEquals(Connection.TRANSACTION_SERIALIZABLE, leg.getTransactionIsolation());
        assertTrue(ranOn(leg, "SET_LOCK_TIMEOUT 7"));
        assertTrue(ranOn(leg, "SET_CAS_CHANGE_MODE " + CUBRIDConnection.CAS_CHANGE_MODE_KEEP));
        assertEquals(ResultSet.CLOSE_CURSORS_AT_COMMIT, leg.getHoldability());
        assertEquals(3000, leg.getNetworkTimeout());
        assertEquals(
                "setAutoGeneratedKeys",
                Boolean.TRUE,
                LbTestReflection.field(leg, "isAutoGeneratedKeys"));
    }

    /**
     * r5 D6: like every other session property, a CAS change mode set while the write broker is
     * down moves the write leg and is applied there.
     */
    @Test
    public void aCasChangeModeSetWhileTheWriteBrokerIsDownIsAppliedOnTheNewWriteLeg()
            throws Exception {
        final LoadBalanceConnection conn = kit.open("readWeight=slave:1");
        kit.server.fault(kit.rw(1), KitServer.Fault.REFUSE);

        conn.setCASChangeMode(CUBRIDConnection.CAS_CHANGE_MODE_KEEP);

        assertEquals(kit.rw(2), conn.getCurrentRwEndpoint().getId());
        assertTrue(
                ranOn(
                        liveLegOn(kit.rw(2)),
                        "SET_CAS_CHANGE_MODE " + CUBRIDConnection.CAS_CHANGE_MODE_KEEP));
    }

    private KitConnection liveLegOn(final String endpoint) {
        KitConnection found = null;
        for (KitConnection c : kit.server.live()) {
            if ((c.kitU().node().host() + ":" + c.kitU().node().port()).equals(endpoint)) {
                found = c;
            }
        }
        assertTrue("no live leg on " + endpoint, found != null);
        return found;
    }

    private boolean ranOn(final KitConnection leg, final String request) {
        for (KitServer.Request r : kit.server.requests()) {
            if (r.physical == leg.serial() && r.code == 0 && r.what.equals(request)) {
                return true;
            }
        }
        return false;
    }
}
